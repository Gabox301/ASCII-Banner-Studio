// NewPyramidFont es la fuente FIGlet 'pyramid' (nombre visible 'Pyramid').
// Generada desde pyfiglet para ampliar la variedad de ASCII.
// Altura: 3. Incluye 95 glyphs ASCII imprimibles (32..126) donde la fuente original los define;
// los ausentes usan el fallback '?' del motor sin panics.
func NewPyramidFont() domain.Font {
	return domain.Font{
		ID:         "pyramid",
		Name:       "Pyramid",
		Height:     3,
		Characters: buildFigletCharacters(figlet_pyramidPatterns),
		Fallback:   '?',
	}
}

