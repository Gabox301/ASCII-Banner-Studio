// NewDigitalFont es la fuente FIGlet 'digital' (nombre visible 'Digital').
// Generada desde pyfiglet para ampliar la variedad de ASCII.
// Altura: 3. Incluye 95 glyphs ASCII imprimibles (32..126) donde la fuente original los define;
// los ausentes usan el fallback '?' del motor sin panics.
func NewDigitalFont() domain.Font {
	return domain.Font{
		ID:         "digital",
		Name:       "Digital",
		Height:     3,
		Characters: buildFigletCharacters(figlet_digitalPatterns),
		Fallback:   '?',
	}
}

